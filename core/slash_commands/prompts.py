"""提示词类斜杠命令的模板与展开函数。

这些命令不直接执行本地动作，而是把用户参数填进一段固定的中文提示词，
再当作一次普通回合交给模型。模板集中放这里，而不是散在 specs 的 handler
里，是因为提示词是要反复打磨的文案：单独成文件便于 review 与调参，
也避免 handler 与文案互相牵制。

填充刻意使用 str.replace 而不是 str.format：模板里会出现 JSON 示例等
字面花括号，format 会把它当成占位符而抛 KeyError。
"""

from typing import Dict

# 命令名 -> 完整提示词模板，模板内用 {args} 标记用户参数位置。
TEMPLATES: Dict[str, str] = {
    "/fix": (
        "请修复下面的问题。\n"
        "\n"
        "问题描述/报错原文：\n"
        "{args}\n"
        "\n"
        "要求：\n"
        "1. 先定位根因，不要一上手就改代码：完整读一遍报错与相关日志，尝试复现问题，"
        "并查看最近的相关变更（git log / git diff），确认是哪一处逻辑或契约被破坏。\n"
        "2. 用一句话说明根因，再动手修复；修复应是满足根因的最小改动，"
        "不要顺手重构无关代码，也不要靠吞掉异常、放宽断言来掩盖问题。\n"
        "3. 改完必须跑验证（相关的单元测试或可复现命令），并把实际执行的命令与输出贴出来；"
        "如果没有可用的验证手段，明确说明你做了什么替代验证。\n"
        "4. 最后总结：根因、改了哪些文件、验证结果、以及是否还有遗留风险。"
    ),
    "/review": (
        "请审查以下范围：\n"
        "{args}\n"
        "\n"
        "要求：\n"
        "1. 按严重程度从高到低排序输出问题（阻断性/正确性 > 数据与安全 > 可维护性 > 风格），"
        "不要按文件顺序罗列。\n"
        "2. 每个问题都要给出可核对的位置，格式为 `path/to/file.py:行号`，"
        "并说明触发条件与影响，再给出具体修复建议（能给出改后代码更好）。\n"
        "3. 只报告你能在代码里证实的问题；不确定的标为“待确认”并说明还需要看什么，不要臆测。\n"
        "4. 先给结论：这次改动是否可以合并；有明显缺陷时明确说不行并列出必须先修的点。\n"
        "5. 最后附一句“未发现问题”的说明仅在你确实检查过时使用，并写明检查了哪些文件。"
    ),
    "/init": (
        "请为当前项目生成一份 AGENTS.md。\n"
        "\n"
        "补充说明（可选）：\n"
        "{args}\n"
        "\n"
        "要求：\n"
        "1. 先扫描项目结构，识别技术栈、依赖管理方式、入口文件、目录职责、"
        "测试与构建/校验命令，以及代码风格与提交约定。\n"
        "2. 生成的 AGENTS.md 要写清：项目概述、关键目录、常用命令（安装/运行/测试/静态检查）、"
        "开发规约、以及改动代码时必须遵守的注意事项。\n"
        "3. 内容必须基于项目里真实存在的文件与配置，不要编造命令；"
        "找不到的信息写“未发现”，并说明你是怎么找的。\n"
        "4. 这份 AGENTS.md 先作为草稿展示给我确认，确认后再落盘，不要直接写入文件。"
    ),
    "/test": (
        "请运行并修好测试，关注范围为：\n"
        "{args}\n"
        "\n"
        "要求：\n"
        "1. 先确认本项目的测试命令（看 README、pyproject.toml / package.json 等配置），"
        "不要凭空猜一个命令就开跑。\n"
        "2. 跑一遍，拿到真实的失败列表；逐个分析失败原因，区分“测试写错了”与“代码有 bug”，"
        "并说明你的判断依据。\n"
        "3. 修复只针对根因，改动尽可能小；不许删改断言、不许加 skip/xfail、"
        "不许放宽超时或降低精度来让测试变绿。\n"
        "4. 修完重跑，贴出实际执行的命令与结果输出；仍有失败就如实说明剩余失败及原因。\n"
        "5. 最后总结：失败总数、真实修复数、被判定为测试本身有误的数量与处理方式。"
    ),
    "/explain": (
        "请解释这段代码/这个功能：\n"
        "{args}\n"
        "\n"
        "要求：\n"
        "1. 如果给的线索不足以定位代码位置，先向我确认具体文件与函数，不要猜着解释。\n"
        "2. 定位到目标后，先读它的调用方与被调用方，再解释：它在整体链路中承担什么职责、"
        "输入输出契约是什么、有哪些隐含假设与副作用。\n"
        "3. 解释顺序为：一句话定位 -> 数据怎么流动 -> 关键分支与边界情况 -> 容易踩的坑。\n"
        "4. 引用代码时带上 `file:line`，便于我对照；不确定的地方明确标注为推测。"
    ),
}

# 用户只输入命令名时用的兜底参数，让模板不说半句话。
# 只给需要宾语的三条：/fix 与 /init 不兜底，因为“没有报错原文/没有补充说明”
# 本身就是要表达的信息，硬塞默认值反而会带偏模型。
_DEFAULT_ARGS: Dict[str, str] = {
    "/review": "当前工作区的改动",
    "/test": "相关",
    "/explain": "你指定的",
}


def build_prompt(name: str, args: str) -> str:
    """把用户参数填进对应模板，返回最终提示词；未知命令返回空串。

    名称做去空格 + 小写归一，是因为 CLI 允许 `/FIX` 这类写法，且解析层已保证
    大小写不敏感；返回空串而不是抛异常，是为了让入口统一走“未注册命令”分支，
    不必为文案缺失写 try/except。
    """
    key = str(name or "").strip().lower()
    template = TEMPLATES.get(key)
    if template is None:
        return ""

    text = str(args or "").strip()
    if not text:
        text = _DEFAULT_ARGS.get(key, "")

    # 用 replace 而非 format：模板含字面花括号，format 会误判为占位符。
    return template.replace("{args}", text)
